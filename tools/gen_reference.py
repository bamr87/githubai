#!/usr/bin/env python3
"""gen_reference.py: generate docs/reference/ from the framework's own source files.

The reusable workflows' `workflow_call` contract (inputs, secrets), their
triggers, job permissions, timeouts and concurrency, and the default label
taxonomy are public API (AGENTS.md, "Public API"). Copied by hand into the docs
they drift from the files that define them, so this script derives them:

  docs/reference/workflows.md  from .github/workflows/claude*.yml
  docs/reference/labels.md     from profiles/_base.yml labels.taxonomy

Usage:
  python3 tools/gen_reference.py           rewrite the generated files
  python3 tools/gen_reference.py --check   exit 1 when a generated file is stale

tests/test_reference.py runs the check, so a workflow input or label change that
skips the regeneration fails CI. Needs PyYAML (requirements-dev.txt).
"""

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "docs" / "reference"
COMMAND = "python3 tools/gen_reference.py"


def header(source: str) -> str:
    return f"<!-- GENERATED by `{COMMAND}` from {source} — do not edit by hand -->"


def cell(value) -> str:
    """One Markdown table cell: no newlines, escaped pipes, an em dash for empty."""
    if value is None or value == "":
        return "—"
    text = " ".join(str(value).split())
    return text.replace("|", "\\|")


def load(path: Path):
    with path.open(encoding="utf-8") as fh:
        return yaml.safe_load(fh)


def triggers(on: dict) -> str:
    parts = []
    for event, spec in on.items():
        detail = []
        if isinstance(spec, dict):
            if spec.get("types"):
                detail.append(", ".join(spec["types"]))
            if spec.get("tags"):
                detail.append("tags " + ", ".join(f"`{t}`" for t in spec["tags"]))
        elif isinstance(spec, list) and event == "schedule":
            detail.append(", ".join(f"cron `{entry['cron']}`" for entry in spec))
        parts.append(f"`{event}`" + (f" ({'; '.join(detail)})" if detail else ""))
    return " · ".join(parts)


def inputs_table(inputs: dict) -> list[str]:
    rows = ["| Input | Type | Required | Default | Description |", "| --- | --- | --- | --- | --- |"]
    for name, spec in inputs.items():
        kind = spec.get("type", "string")
        if spec.get("options"):
            kind += " (" + ", ".join(f"`{o}`" for o in spec["options"]) + ")"
        default = spec.get("default")
        rows.append(
            f"| `{name}` | {cell(kind)} | {'yes' if spec.get('required') else 'no'} | "
            f"{cell(f'`{default}`' if default not in (None, '') else None)} | {cell(spec.get('description'))} |"
        )
    return rows


def secrets_table(secrets: dict) -> list[str]:
    rows = ["| Secret | Required | Description |", "| --- | --- | --- |"]
    for name, spec in secrets.items():
        spec = spec or {}
        rows.append(f"| `{name}` | {'yes' if spec.get('required') else 'no'} | {cell(spec.get('description'))} |")
    return rows


def jobs_table(doc: dict) -> list[str]:
    rows = ["| Job | Permissions | Timeout (min) |", "| --- | --- | --- |"]
    for name, job in doc.get("jobs", {}).items():
        perms = job.get("permissions", doc.get("permissions")) or {}
        if isinstance(perms, dict):
            grants = ", ".join(f"`{scope}: {level}`" for scope, level in sorted(perms.items()))
        else:
            grants = f"`{perms}`"
        rows.append(f"| `{name}` | {cell(grants)} | {cell(job.get('timeout-minutes'))} |")
    return rows


def render_workflows() -> str:
    lines = [
        header("`.github/workflows/claude*.yml`"),
        "# Reusable workflow contract",
        "",
        (
            "> The triggers, `workflow_call` inputs and secrets, job permissions, timeouts and concurrency"
            " of every `claude*.yml` workflow, generated from the workflow files."
        ),
        "",
        (
            "What each workflow does, and the gates behind each trigger, is explained in"
            " [docs/workflows.md](../workflows.md). Everything listed here is public API: add, don't rename."
            " A caller passes `secrets: inherit` and grants its job at least the permissions below, because a"
            " reusable workflow cannot exceed its caller's grants."
        ),
    ]
    for path in sorted((ROOT / ".github" / "workflows").glob("claude*.yml")):
        doc = load(path)
        # PyYAML reads the bare key `on` as the boolean True.
        on = doc.get(True) or doc.get("on") or {}
        call = on.get("workflow_call") or {}
        dispatch = on.get("workflow_dispatch") or {}
        lines += ["", f"## `{path.name}` — {doc.get('name', path.stem)}", ""]
        if "workflow_call" in on:
            lines += [f"Call it as `uses: bamr87/githubai/.github/workflows/{path.name}@main`.", ""]
        lines += [f"**Triggers:** {triggers(on)}", ""]
        if call.get("inputs"):
            lines += ["**`workflow_call` inputs:**", ""] + inputs_table(call["inputs"]) + [""]
        elif "workflow_call" in on:
            lines += ["**`workflow_call` inputs:** none.", ""]
        if dispatch.get("inputs"):
            lines += ["**`workflow_dispatch` inputs:**", ""] + inputs_table(dispatch["inputs"]) + [""]
        if call.get("outputs"):
            lines += ["**Outputs:** " + ", ".join(f"`{n}`" for n in call["outputs"]), ""]
        if call.get("secrets"):
            lines += ["**Secrets:**", ""] + secrets_table(call["secrets"]) + [""]
        lines += ["**Jobs:**", ""] + jobs_table(doc) + [""]
        concurrency = doc.get("concurrency")
        if isinstance(concurrency, dict):
            cancel = "yes" if concurrency.get("cancel-in-progress") else "no"
            lines.append(f"**Concurrency:** group `{concurrency.get('group')}`; cancel in progress: {cancel}.")
        elif concurrency:
            lines.append(f"**Concurrency:** group `{concurrency}`.")
        else:
            lines.append("**Concurrency:** none at workflow level.")
    return "\n".join(lines).rstrip() + "\n"


def render_labels() -> str:
    labels = load(ROOT / "profiles" / "_base.yml")["labels"]
    lines = [
        header("`profiles/_base.yml` `labels.taxonomy`"),
        "# Label taxonomy",
        "",
        (
            "> The default label set (name, color, meaning) that profiles inherit and `setup/install.sh --labels`"
            " creates, generated from `profiles/_base.yml`."
        ),
        "",
        (
            "The installer's `LABELS` list must match this taxonomy (`tests/test_installer.py`)."
            f" Labels that start with `{labels.get('prefix', 'claude:')}` are the automation's control plane;"
            " [docs/security.md](../security.md) explains who can authorize what."
        ),
        "",
        "| Label | Color | Meaning |",
        "| --- | --- | --- |",
    ]
    for entry in labels["taxonomy"]:
        lines.append(f"| `{entry['name']}` | `#{entry['color']}` | {cell(entry.get('description'))} |")
    return "\n".join(lines) + "\n"


OUTPUTS = {"workflows.md": render_workflows, "labels.md": render_labels}


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="exit 1 when a generated file is stale")
    args = parser.parse_args()
    stale = []
    for name, render in OUTPUTS.items():
        path = OUT_DIR / name
        text = render()
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if args.check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(ROOT)}")
    if stale:
        print(f"stale: {', '.join(stale)}; run `{COMMAND}`", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
